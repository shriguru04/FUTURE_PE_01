import { SECTIONS } from '../data/options.js';

const bullets = (arr) => arr.map((x) => `- ${x}`).join('\n');

const FORMATTERS = {
  homepage: (c, md) => [
    md ? `# ${c.heroHeadline}` : `HEADLINE: ${c.heroHeadline}`,
    c.subheadline,
    `Primary CTA: ${c.primaryCta}`,
    `Secondary CTA: ${c.secondaryCta}`,
    md ? `## Value proposition\n${c.valueProposition}` : `VALUE PROPOSITION: ${c.valueProposition}`,
    md ? `## Key benefits\n${bullets(c.keyBenefits)}` : `KEY BENEFITS:\n${bullets(c.keyBenefits)}`,
    md ? `## Suggested section headings\n${bullets(c.sectionHeadings)}` : `SECTION HEADINGS:\n${bullets(c.sectionHeadings)}`,
  ],
  about: (c, md) => [
    c.introduction,
    md ? `## Mission\n${c.mission}` : `MISSION: ${c.mission}`,
    md ? `## What sets us apart\n${bullets(c.differentiators)}` : `DIFFERENTIATORS:\n${bullets(c.differentiators)}`,
    c.customerMessage,
  ],
  services: (c, md) =>
    c.services.map((s) => `${md ? '### ' : ''}${s.name}\n${s.description}\nBenefit: ${s.benefit}\nCTA: ${s.cta}`),
  cta: (c) => [`Primary: ${c.primary}`, `Secondary: ${c.secondary}`, `Contact: ${c.contact}`, `Booking: ${c.booking}`, `Enquiry: ${c.enquiry}`],
  contact: (c, md) => [
    md ? `### ${c.heading}` : `HEADING: ${c.heading}`,
    c.supportingText,
    md ? `Form labels:\n${bullets(c.formLabels)}` : `FORM LABELS:\n${bullets(c.formLabels)}`,
    `Button: ${c.buttonText}`,
  ],
};

export function sectionToText(section, content, { markdown = false } = {}) {
  return FORMATTERS[section](content, markdown).join('\n\n');
}

export function exportAll({ businessName, sections, format = 'txt', modeLabel = 'Demo mode (template-generated, no AI model)' }) {
  const md = format === 'md';
  const parts = [];
  parts.push(md ? `# ${businessName}: website copy` : `${businessName.toUpperCase()}: WEBSITE COPY`);
  parts.push(`Generated by CopyCraft AI. ${modeLabel}.`);
  for (const { id, label } of SECTIONS) {
    if (!sections[id]) continue;
    parts.push(md ? `## ${label}` : `==== ${label.toUpperCase()} ====`);
    parts.push(sectionToText(id, sections[id], { markdown: md }));
  }
  return parts.join('\n\n') + '\n';
}

export function safeFilename(name, ext) {
  const base = String(name || 'website-copy').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 50) || 'website-copy';
  return `${base}-copy.${ext}`;
}

export function downloadFile(filename, text, mime = 'text/plain') {
  const url = URL.createObjectURL(new Blob([text], { type: `${mime};charset=utf-8` }));
  const a = Object.assign(document.createElement('a'), { href: url, download: filename });
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
